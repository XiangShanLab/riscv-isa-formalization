# -*- coding: utf-8 -*-
import sys
classes = ['-∞','-N','-S','-0','+0','+S','+N','+∞','sNaN','qNaN']
cond = {
 '-∞':'s=1, e=全1, f=0',
 '-N':'s=1, 0<e<全1',
 '-S':'s=1, e=0, f≠0',
 '-0':'s=1, e=0, f=0',
 '+0':'s=0, e=0, f=0',
 '+S':'s=0, e=0, f≠0',
 '+N':'s=0, 0<e<全1',
 '+∞':'s=0, e=全1, f=0',
 'sNaN':'e=全1, f≠0, f 最高位=0',
 'qNaN':'e=全1, f≠0, f 最高位=1',
}

L = []
A = L.append
A('### 2.5 组合数')
A('')
A('组合是各个集合的笛卡尔积。下面把配置组合、操作数组合、装箱组合、访存组合逐表列出；每张表都把该类情况列全，不做抽样。')
A('')
A('#### 2.5.1 配置组合（46 类）')
A('')
A('| `mstatus.FS` | `rm` / `fcsr.frm` | 可执行 | 类数 |')
A('|---|---|---|---:|')
A('| 0 | 任意 | 否 | 1 |')
A('| 1, 2, 3 | `rm∈{0,1,2,3,4}`（静态舍入） | 是 | $3\\times5=15$ |')
A('| 1, 2, 3 | `rm=7, fcsr.frm∈{0,1,2,3,4}`（动态舍入） | 是 | $3\\times5=15$ |')
A('| 1, 2, 3 | `rm∈{5,6}` | 否 | $3\\times2=6$ |')
A('| 1, 2, 3 | `rm=7, fcsr.frm∈{5,6,7}` | 否 | $3\\times3=9$ |')
A('| **合计** | | 30 可执行 / 16 不可执行 | **46** |')
A('')
A('说明：前两行是 30 个可执行配置类；后三行是不可执行类（1 个 $FS=0$、6 个 `rm` 保留、9 个动态 `frm` 保留）。`impl(I)`、`virt`、stateen 是公式里额外的二值使能条件，不参与这 46 类的计数。')
A('')
A('#### 2.5.2 一元操作数组合（10 组）')
A('')
A('| # | 类 | 代码 | 位域条件 |')
A('|---:|---|---|---|')
for i,c in enumerate(classes,1):
    A('| %d | %s | `%s` | %s |' % (i, c if c not in ('sNaN','qNaN') else ('信号 NaN' if c=='sNaN' else '静默 NaN'), c, cond[c]))
A('')
A('#### 2.5.3 二元操作数组合（$10\\times10=100$ 组）')
A('')
A('行是 $a$ 的类，列是 $b$ 的类；格中的 `a/b` 就是一个组合，10×10 共 100 个。')
A('')
A('| $a$ \\ $b$ | ' + ' | '.join(classes) + ' |')
A('|---|' + '---|'*10)
for a in classes:
    A('| **%s** | ' % a + ' | '.join('%s/%s' % (a,b) for b in classes) + ' |')
A('')
A('#### 2.5.4 三元操作数组合（$10\\times10\\times10=1000$ 组）')
A('')
A('行是 $(a,b)$ 的 100 个二元组，列是 $c$ 的 10 个类；格中 `✓` 表示三元组 $(a,b,c)$ 存在。共 $100\\times10=1000$ 个。')
A('')
A('| $a/b$ \\ $c$ | ' + ' | '.join(classes) + ' |')
A('|---|' + '---|'*10)
for a in classes:
    for b in classes:
        A('| **%s/%s** | ' % (a,b) + ' | '.join('✓' for _ in classes) + ' |')
A('')
A('#### 2.5.5 装箱组合')
A('')
A('装箱只影响窄格式：同一个值在宽寄存器里可能是合法装箱，也可能是非法装箱（解箱为 `qNaN` 并置 `NV`）。每个窄操作数的因子是 2。')
A('')
A('| 值格式 | FLEN=32 | FLEN=64 | FLEN=128 |')
A('|---|---:|---:|---:|')
A('| H | 2（合法/非法） | 2 | 2 |')
A('| S | 1（满宽） | 2 | 2 |')
A('| D | 不可用 | 1（满宽） | 2 |')
A('| Q | 不可用 | 不可用 | 1（满宽） |')
A('')
A('#### 2.5.6 其他操作数集合')
A('')
A('| 集合 | 组成 | 大小 |')
A('|---|---|---:|')
A('| $\\mathcal O_{\\mathrm{int}}$（W/WU） | 32 位位型 | $2^{32}$ |')
A('| $\\mathcal O_{\\mathrm{int}}$（L/LU，RV64） | 64 位位型 | $2^{64}$ |')
A('| $\\mathcal O_{\\mathrm{FLI}}$ | 5 位索引 | 32 |')
A('| $\\mathcal O_{\\mathrm{mem}}$ | 对齐 2 × 翻译 4 × PMP/PMA 2 × 断点 2 | $2\\times4\\times2\\times2=32$ |')
A('')
A('$\\mathcal O_{\\mathrm{mem}}$ 的 32 种是上界；其中“翻译失败”与“PMP/PMA 拒绝”等组合不会同时成立，实际可行子集见 3.19/3.20 的表。')
A('')
A('#### 2.5.7 组合总数')
A('')
A('表中“全装箱”指每个操作数都取窄格式（因子 2）的最坏情况；满宽格式的因子是 1。')
A('')
A('| 元数 | 值类组合 | 全装箱因子 | 全装箱组合 | 可执行配置 | 配置×不装箱 | 配置×全装箱 |')
A('|---|---:|---:|---:|---:|---:|---:|')
A('| 一元 | 10 | $2$ | 20 | 30 | 300 | 600 |')
A('| 二元 | $10^2=100$ | $2^2=4$ | 400 | 30 | 3000 | 12000 |')
A('| 三元 | $10^3=1000$ | $2^3=8$ | 8000 | 30 | 30000 | 240000 |')
A('')
A('“配置×操作数”只统计带 `rm` 的算术指令；无 `rm` 的指令（`FMIN`、比较、`FCLASS`、`FSGNJ`、`FLI`、CSR 访问）用 3 个 FS 可执行值，不乘 `rm` 因子。load/store 的操作数是 $\\mathcal O_{\\mathrm{mem}}$，按 3.19/3.20 的 8 行分别计数。')
A('')

new = '\n'.join(L)
