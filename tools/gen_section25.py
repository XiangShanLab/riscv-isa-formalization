# -*- coding: utf-8 -*-
import sys
classes = ['-∞','-N','-S','-0','+0','+S','+N','+∞','sNaN','qNaN']
label = {'-∞':'负无穷','-N':'负正规','-S':'负次正规','-0':'负零','+0':'正零',
         '+S':'正次正规','+N':'正正规','+∞':'正无穷','sNaN':'信号 NaN','qNaN':'静默 NaN'}
cond = {'-∞':'s=1, e=全1, f=0','-N':'s=1, 0<e<全1','-S':'s=1, e=0, f≠0',
        '-0':'s=1, e=0, f=0','+0':'s=0, e=0, f=0','+S':'s=0, e=0, f≠0',
        '+N':'s=0, 0<e<全1','+∞':'s=0, e=全1, f=0',
        'sNaN':'e=全1, f≠0, f 最高位=0','qNaN':'e=全1, f≠0, f 最高位=1'}

L=[]; A=L.append
A('### 2.5 组合数')
A('')
A('一条指令的输入由两部分相乘得到：')
A('')
A('$$')
A('\\text{输入组合}=\\underbrace{C}_{\\text{配置}}\\times\\underbrace{O_1\\times O_2\\times\\cdots\\times O_n}_{\\text{各源操作数}}.')
A('$$')
A('')
A('配置与各操作数彼此独立，所以组合数就是各维大小的乘积。下面先把每一维的全部取值列成表，再逐层相乘；这样“为什么是 10、100、1000、3000”都能对到具体的表行，而不是只给一个数字。')
A('')
A('#### 2.5.1 配置维（46 类）')
A('')
A('| `mstatus.FS` | `rm` / `fcsr.frm` | 可执行 | 类数 |')
A('|---|---|---|---:|')
A('| 0 | 任意 | 否 | 1 |')
A('| 1, 2, 3 | `rm∈{0,1,2,3,4}`（静态舍入） | 是 | $3\\times5=15$ |')
A('| 1, 2, 3 | `rm=7, fcsr.frm∈{0,1,2,3,4}`（动态舍入） | 是 | $3\\times5=15$ |')
A('| 1, 2, 3 | `rm∈{5,6}` | 否 | $3\\times2=6$ |')
A('| 1, 2, 3 | `rm=7, fcsr.frm∈{5,6,7}` | 否 | $3\\times3=9$ |')
A('| **合计** | | 30 可执行 / 16 不可执行 | **46** |')
A('')
A('推导：`FS` 有 4 个取值；`rm`/`frm` 有 15 个等价类（静态 5、保留 2、动态 8）。若直接相乘是 $4\\times15=60$，但 `FS=0` 时 `rm` 不再起作用，这 15 类并成 1 类，所以总数是 $1+3\\times15=46$。')
A('')
A('`FS=0` 的 1 类、`rm∈{5,6}` 的 6 类、动态保留的 9 类都不可执行；静态与动态合法舍入的 $15+15=30$ 类可执行。`impl(I)`、`virt`、stateen 是公式里的二值使能项，不属于这 46 类，见 1.2。')
A('')
A('#### 2.5.2 操作数维（每个源操作数 10 类）')
A('')
A('| # | 类 | 代码 | 位域条件 |')
A('|---:|---|---|---|')
for i,c in enumerate(classes,1):
    A('| %d | %s | `%s` | %s |' % (i,label[c],c,cond[c]))
A('')
A('这 10 类由字段取值互斥且穷尽地划分：先看指数是否全 1，再看尾数是否为 0，最后看符号位。因此一个操作数恰好落在其中一类。$n$ 个源操作数就有 $10^n$ 种值类组合：一元 10、二元 100、三元 1000。')
A('')
A('#### 2.5.3 二元组合（$10\\times10=100$ 组）')
A('')
A('下表行是 $a$ 的类，列是 $b$ 的类，格中的 `a/b` 就是一个组合。100 个格就是 100 个组合；因为 `a`、`b` 是两个独立寄存器，任何一行与任何一列都能同时出现，所以不存在空格。')
A('')
A('| $a$ \\ $b$ | ' + ' | '.join(classes) + ' |')
A('|---|' + '---|'*10)
for a in classes:
    A('| **%s** | ' % a + ' | '.join('%s/%s'%(a,b) for b in classes) + ' |')
A('')
A('#### 2.5.4 三元组合（$10\\times10\\times10=1000$ 组）')
A('')
A('三元组合不逐个列 1000 格，因为它就是 2.5.3 的表再乘一个独立的操作数：')
A('')
A('| 维 | 取值 | 数量 |')
A('|---|---|---:|')
A('| $(a,b)$ | 2.5.3 的二维表 | 100 |')
A('| $c$ | 2.5.2 的 10 个类 | 10 |')
A('| **合计** | 直积 $(a,b)\\times c$ | **1000** |')
A('')
A('也就是说：2.5.3 的每一行（一个 $(a,b)$ 组合）都与 2.5.2 的 10 个 $c$ 类各配一次，得到 10 个三元组；100 行共 1000 个。三步的源寄存器互相独立，没有额外约束，所以不需要像访存那样按上下文剔除不可行项。')
A('')
A('#### 2.5.5 装箱维')
A('')
A('装箱只在“值的宽度小于寄存器宽度”时产生第二个取值（合法装箱/非法装箱）。非法装箱解箱为 `qNaN` 并置 `NV`。因此每个窄操作数给组合数乘 2，满宽操作数乘 1。')
A('')
A('| 值格式 | FLEN=32 | FLEN=64 | FLEN=128 |')
A('|---|---:|---:|---:|')
A('| H | 2（合法/非法） | 2 | 2 |')
A('| S | 1（满宽） | 2 | 2 |')
A('| D | 不可用 | 1（满宽） | 2 |')
A('| Q | 不可用 | 不可用 | 1（满宽） |')
A('')
A('#### 2.5.6 其他操作数维')
A('')
A('| 集合 | 组成 | 大小 |')
A('|---|---|---:|')
A('| $\\mathcal O_{\\mathrm{int}}$（W/WU） | 32 位位型 | $2^{32}$ |')
A('| $\\mathcal O_{\\mathrm{int}}$（L/LU，RV64） | 64 位位型 | $2^{64}$ |')
A('| $\\mathcal O_{\\mathrm{FLI}}$ | 5 位索引 | 32 |')
A('| $\\mathcal O_{\\mathrm{mem}}$ | 对齐 2 × 翻译 4 × PMP/PMA 2 × 断点 2 | $2\\times4\\times2\\times2=32$ |')
A('')
A('$\\mathcal O_{\\mathrm{mem}}$ 的 32 是上界；“翻译失败”与“PMP/PMA 拒绝”等组合不会同时成立，实际可行子集按优先级取 3.19/3.20 表中的第一行。')
A('')
A('#### 2.5.7 组合总数')
A('')
A('把 2.5.1–2.5.5 各维相乘。表中“全装箱”指每个操作数都取窄格式（因子 2）的最坏情况；满宽格式因子为 1。')
A('')
A('| 元数 | 值类组合 | 全装箱因子 | 全装箱组合 | 可执行配置 | 配置×不装箱 | 配置×全装箱 |')
A('|---|---:|---:|---:|---:|---:|---:|')
A('| 一元 | 10 | $2$ | 20 | 30 | 300 | 600 |')
A('| 二元 | $10^2=100$ | $2^2=4$ | 400 | 30 | 3000 | 12000 |')
A('| 三元 | $10^3=1000$ | $2^3=8$ | 8000 | 30 | 30000 | 240000 |')
A('')
A('举例：')
A('')
A('- `FADD` 是二元、带 `rm`、S 操作数满宽：$30\\times100=3000$ 组。')
A('- `FADD.H` 在 FLEN=32 的寄存器里有合法/非法装箱：$30\\times(10\\times2)^2=12000$ 组。')
A('- `FSQRT` 是一元、带 `rm`：$30\\times10=300$ 组（全装箱 600）。')
A('- `FMA` 是三元、带 `rm`：$30\\times1000=30000$ 组（全装箱 240000）。')
A('- `FMIN`、比较、`FCLASS`、`FSGNJ`、`FLI`、CSR 访问没有 `rm`，配置维只按 `mstatus.FS` 的 3 个可执行值计，不再乘舍入类。')
A('')
A('若把 H/S/D/Q 分开计，再乘以该指令支持的格式数（3.0.1 的 `Formats(I)`）；各格式的操作数位宽不同，但值类划分相同，所以每个格式都是一张完整的 10/100/1000 表。')
A('')

